class TeeLogger:
    """Mirror prints to notebook output and a log file under /kaggle/working."""

    def __init__(self, path: str | Path):
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.file = self.path.open('a', encoding='utf-8')

    def write(self, message: str) -> None:
        print(message, end='', flush=True)
        self.file.write(message)
        self.file.flush()

    def line(self, message: str = '') -> None:
        self.write(message + '\n')

    def close(self) -> None:
        self.file.close()


def load_jsonl(path: str | Path) -> list[dict]:
    path = Path(path)
    if not path.exists():
        raise FileNotFoundError(
            f'test.jsonl not found: {path}\n'
            'Set CFG.comp_math_test_jsonl or environment variable COMP_MATH_TEST_JSONL to your JSONL path. '
            'Example Kaggle input path: /kaggle/input/comp-math-test/test.jsonl'
        )

    rows = []
    with path.open('r', encoding='utf-8') as f:
        for line_no, line in enumerate(f, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f'Invalid JSON on line {line_no}: {exc}') from exc
            if 'id' not in obj or 'problem' not in obj:
                raise ValueError(f'Line {line_no} must contain at least "id" and "problem" fields.')
            rows.append(obj)

    return rows


def normalize_answer(value):
    if value is None:
        return None
    text = str(value).strip()
    boxed = re.findall(r'\\boxed\{([^{}]+)\}', text)
    if boxed:
        text = boxed[-1].strip()
    text = text.replace('$', '').strip()
    if re.fullmatch(r'[+-]?\d+', text):
        return str(int(text))
    return text


def write_jsonl(path: str | Path, rows: list[dict]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', encoding='utf-8') as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + '\n')


def existing_completed_ids(predictions_jsonl: Path) -> set[str]:
    if not predictions_jsonl.exists():
        return set()
    done = set()
    with predictions_jsonl.open('r', encoding='utf-8') as f:
        for line in f:
            if line.strip():
                done.add(json.loads(line)['id'])
    return done


def run_comp_math_jsonl(
    solver: AIMO3Solver,
    test_jsonl: str | Path = None,
    output_dir: str | Path = None,
    limit: int | None = None,
) -> tuple[pd.DataFrame, dict]:
    """Run baseline AIMO3Solver over Comp-Math JSONL lines and save predictions + metrics."""

    test_jsonl = Path(test_jsonl or CFG.comp_math_test_jsonl)
    output_dir = Path(output_dir or CFG.comp_math_output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    predictions_jsonl = output_dir / 'predictions.jsonl'
    predictions_csv = output_dir / 'predictions.csv'
    metrics_json = output_dir / 'metrics.json'
    attempts_jsonl = output_dir / 'attempt_details.jsonl'
    log_path = output_dir / 'run.log'

    logger = TeeLogger(log_path)
    started_at = datetime.now(timezone.utc)

    try:
        rows = load_jsonl(test_jsonl)
        if limit is not None:
            rows = rows[:limit]

        solver.problems_remaining = len(rows)
        completed = existing_completed_ids(predictions_jsonl) if CFG.resume else set()
        logger.line(f'Loaded {len(rows)} problems from {test_jsonl}')
        logger.line(f'Output dir: {output_dir}')
        if completed:
            logger.line(f'Resume enabled: skipping {len(completed)} already completed ids')

        all_predictions = []
        if predictions_jsonl.exists() and CFG.resume:
            with predictions_jsonl.open('r', encoding='utf-8') as f:
                all_predictions = [json.loads(line) for line in f if line.strip()]

        for idx, row in enumerate(rows, start=1):
            problem_id = str(row['id'])
            if problem_id in completed:
                continue

            problem_text = str(row['problem'])
            subset = row.get('subset_for_metrics')
            expected = row.get('expected_answer')

            logger.line('=' * 100)
            logger.line(f'[{idx}/{len(rows)}] id={problem_id} subset={subset}')
            logger.line(f'Problem preview: {problem_text[:240]}')
            problem_start = time.time()

            try:
                gc.disable()
                answer = solver.solve_problem(problem_text)
            except Exception as exc:
                answer = 0
                logger.line(f'ERROR while solving {problem_id}: {repr(exc)}')
            finally:
                gc.enable()
                gc.collect()

            elapsed = round(time.time() - problem_start, 3)
            pred_norm = normalize_answer(answer)
            expected_norm = normalize_answer(expected)
            is_correct = None if expected is None else (pred_norm == expected_norm)

            pred_row = {
                'id': problem_id,
                'subset_for_metrics': subset,
                'problem': problem_text,
                'answer': answer,
                'normalized_answer': pred_norm,
                'expected_answer': expected,
                'normalized_expected_answer': expected_norm,
                'is_correct': is_correct,
                'elapsed_seconds': elapsed,
            }
            all_predictions.append(pred_row)

            with predictions_jsonl.open('a', encoding='utf-8') as f:
                f.write(json.dumps(pred_row, ensure_ascii=False) + '\n')

            attempt_row = {
                'id': problem_id,
                'attempts': getattr(solver, 'last_detailed_results', []),
                'vote_summary': getattr(solver, 'last_vote_summary', []),
            }
            with attempts_jsonl.open('a', encoding='utf-8') as f:
                f.write(json.dumps(attempt_row, ensure_ascii=False) + '\n')

            status = 'NA' if is_correct is None else ('OK' if is_correct else 'WRONG')
            logger.line(f'Done id={problem_id} answer={answer} expected={expected} status={status} elapsed={elapsed}s')

            pd.DataFrame(all_predictions).to_csv(predictions_csv, index=False)

        df = pd.DataFrame(all_predictions)
        metrics = {
            'started_at_utc': started_at.isoformat(),
            'finished_at_utc': datetime.now(timezone.utc).isoformat(),
            'test_jsonl': str(test_jsonl),
            'output_dir': str(output_dir),
            'num_predictions': int(len(df)),
            'num_with_expected': int(df['is_correct'].notna().sum()) if 'is_correct' in df else 0,
            'accuracy': None,
            'accuracy_by_subset': {},
            'mean_elapsed_seconds': float(df['elapsed_seconds'].mean()) if len(df) else None,
        }

        if len(df) and df['is_correct'].notna().any():
            labeled = df[df['is_correct'].notna()].copy()
            metrics['accuracy'] = float(labeled['is_correct'].mean())
            metrics['accuracy_by_subset'] = (
                labeled.groupby('subset_for_metrics')['is_correct']
                .mean()
                .sort_index()
                .to_dict()
            )

        with metrics_json.open('w', encoding='utf-8') as f:
            json.dump(metrics, f, ensure_ascii=False, indent=2)

        logger.line('=' * 100)
        logger.line('Finished Comp-Math JSONL run')
        logger.line(f'Predictions CSV: {predictions_csv}')
        logger.line(f'Predictions JSONL: {predictions_jsonl}')
        logger.line(f'Attempt details JSONL: {attempts_jsonl}')
        logger.line(f'Metrics JSON: {metrics_json}')
        logger.line(f'Log: {log_path}')
        logger.line(f'Metrics: {json.dumps(metrics, ensure_ascii=False)}')

        return df, metrics

    finally:
        logger.close()

