def compute_experiment_metrics(results):
    total = len(results)
    correct = sum(1 for r in results if r.get("correct") is True)
    incorrect = sum(1 for r in results if r.get("correct") is False)

    latencies = [r.get("latency_ms", 0) for r in results]
    tokens = [r.get("token_count", 0) for r in results]

    return {
        "accuracy": correct / total if total else None,
        "correct": correct,
        "incorrect": incorrect,
        "avg_latency_ms": sum(latencies) / total if total else None,
        "avg_token_count": sum(tokens) / total if total else None,
        "tool_errors": sum(
            1
            for r in results
            for c in r.get("tool_calls", [])
            if c.get("error")
        ),
        "formatting_errors": 0,
    }


def solve_problem_with_trace(problem_text, config):
    old_attempts = CFG.attempts
